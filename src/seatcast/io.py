import re
import time

import duckdb
import pandas as pd

from seatcast import ROOT, RAW, WORK, cfg
from seatcast.clean import anomalies, fare_class, norm, parse_route

CSV = RAW / 'tickets' / 'October-Delhi.csv'
PQ = (WORK / 'tickets.parquet').as_posix()


def md(df):
    cols = [str(c) for c in df.columns]
    rows = [[str(v) for v in r] for r in df.itertuples(index=False)]
    return '\n'.join(['| ' + ' | '.join(cols) + ' |', '|' + '---|' * len(cols)] + ['| ' + ' | '.join(r) + ' |' for r in rows])


def day0():
    sql = (ROOT / 'scripts' / 'day0.sql').read_text(encoding='utf-8').replace('{csv}', CSV.as_posix())
    con = duckdb.connect()
    out = ['# Day-0 checks', '', 'Generated by `python -m seatcast.run day0` from `scripts/day0.sql`. Do not edit by hand.', '']
    for blk in re.split(r'^-- # ', sql, flags=re.M)[1:]:
        title, body = blk.split('\n', 1)
        df = None
        for st in body.split(';\n'):
            if st.strip():
                con.execute(st)
                if con.description:
                    df = con.fetchdf()
        if df is not None:
            out += ['## ' + title, '', md(df), '']
    (ROOT / 'docs' / 'DAY0.md').write_text('\n'.join(out), encoding='utf-8')
    print('wrote docs/DAY0.md')


def cases():
    k = cfg()
    dt = ' '.join(f"WHEN dow IN ({','.join(map(str, d))}) THEN '{n}'" for n, d in k['daytypes'].items())
    hol = ','.join(f"DATE '{h}'" for h in k['holidays'])
    wk = ' '.join(f"WHEN d BETWEEN DATE '{a}' AND DATE '{b}' THEN {i + 1}" for i, (a, b) in enumerate(k['weeks']))
    return dt, hol, wk


def maps(con):
    rows = []
    for (r,) in con.execute('SELECT DISTINCT route FROM t').fetchall():
        rows.append((r, *(parse_route(r) or (None, None, None))))
    con.register('rmap', pd.DataFrame(rows, columns=['route', 'base', 'dir', 'var']))
    nm = con.execute('SELECT start_stop_name FROM t UNION SELECT end_stop_name FROM t').fetchall()
    con.register('nmap', pd.DataFrame([(s, norm(s)) for (s,) in nm if s is not None], columns=['s', 'n']))
    fr = con.execute("""SELECT DISTINCT ROUND(CAST(amount AS DOUBLE) / CAST(passenger_count AS INT), 2) f,
        lower(is_ac) = 'true' a FROM t WHERE CAST(passenger_count AS INT) > 0""").fetchall()
    con.register('fmap', pd.DataFrame([(f, a, fare_class(f, a)) for f, a in fr], columns=['f', 'a', 'fc']))


def load_tickets():
    t0 = time.time()
    WORK.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect()
    con.execute(f"""CREATE TABLE t AS SELECT row_number() OVER () tid, * FROM read_csv('{CSV.as_posix()}',
        header = true, nullstr = ['NULL', ''], all_varchar = true)""")
    maps(con)
    dt, hol, wk = cases()
    slot = cfg()['slot_min']
    con.execute(f"""COPY (
      SELECT tid, pc, ROUND(amt / pc, 2) fare_pp, fc fare_class, ac, v,
        nullif(regexp_extract(v, '^DL[0-9]+[A-Z]+', 0), '') series, route_raw, base, dir, var, ss, es,
        na.n ss_n, nc.n es_n, ts, d date, dow,
        CAST((hour(ts) * 60 + minute(ts)) // {slot} AS INT) slot,
        CASE WHEN d IN ({hol}) THEN 'sunday' {dt} END daytype,
        CASE {wk} END "week",
        pc > 3 f_pc_out, amt = 0 f_zero, ss = es f_same_od
      FROM (SELECT tid, CAST(passenger_count AS INT) pc, CAST(amount AS DOUBLE) amt, lower(is_ac) = 'true' ac,
              vehicle_number v, route route_raw, start_stop_name ss, end_stop_name es,
              CAST(regexp_replace(created_at, '\\+05:30$', '') AS TIMESTAMP) ts,
              CAST(regexp_replace(created_at, '\\+05:30$', '') AS DATE) d,
              isodow(CAST(regexp_replace(created_at, '\\+05:30$', '') AS TIMESTAMP)) - 1 dow
            FROM t WHERE CAST(passenger_count AS INT) > 0) q
      LEFT JOIN rmap ON route = route_raw
      LEFT JOIN fmap ON f = ROUND(amt / pc, 2) AND a = ac
      LEFT JOIN nmap na ON na.s = ss
      LEFT JOIN nmap nc ON nc.s = es
      ORDER BY tid) TO '{PQ}' (FORMAT parquet)""")
    daily = con.execute(f'SELECT date, SUM(pc) pax FROM read_parquet(\'{PQ}\') GROUP BY 1 ORDER BY 1').fetchdf()
    daily['date'] = pd.to_datetime(daily['date']).dt.date
    an = anomalies(daily, cfg()['anomaly_dev'])
    an.to_csv(WORK / 'daily.csv', index=False)
    print('anomaly days:', an[an['flag']][['date', 'daytype', 'dev']].to_dict('records'))
    s = con.execute(f"""SELECT COUNT(*), SUM(pc), SUM(pc) FILTER (WHERE base IS NOT NULL), COUNT(DISTINCT route_raw),
        COUNT(DISTINCT route_raw) FILTER (WHERE base IS NULL), COUNT(DISTINCT base) FROM read_parquet('{PQ}')""").fetchone()
    print('rows, pax, parsed pax, codes, unparsed codes, bases:', s, f'parsed {100 * s[2] / s[1]:.3f}%')
    print(con.execute(f"SELECT route_raw, SUM(pc) FROM read_parquet('{PQ}') WHERE base IS NULL GROUP BY 1 ORDER BY 2 DESC LIMIT 12").fetchall())
    print('stop names raw / normalised:', con.execute('SELECT COUNT(*), COUNT(DISTINCT n) FROM nmap').fetchone())
    print(f'ingest {time.time() - t0:.1f}s')
